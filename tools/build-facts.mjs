// Builds worker/facts-site.js: everything the site itself says about Felipe (bio, experience, clients, education,
// languages, services, every visible project and its soundtrack), as plain text for the Pop quiz (worker/index.js).
// Runs in the deploy after build-pages.mjs, so a new or edited project reaches the quiz with no extra step.
// The output is not committed (.gitignore). Local: `node tools/build-facts.mjs`.
// Felipe's own answers (personal life, opinions, what stays private) live in worker/facts-felipe.js, edited by hand.
import fs from "node:fs";
import vm from "node:vm";

const root = new URL("..", import.meta.url).pathname;
const ctx = { window: {} };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(root + "js/content.js", "utf8"), ctx);
const S = ctx.window.SITE;

// Same slug rule as build-pages.mjs / main.js
const slugOf = p => p.slug || String(p.title.en || p.title).toLowerCase().normalize("NFD")
  .replace(/[̀-ͯ]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const en = v => Array.isArray(v) ? v.map(en).join(", ") : (v && typeof v === "object" ? (v.en ?? "") : (v ?? ""));
const clean = s => String(s).replace(/\s+/g, " ").trim();
const clip = (s, n) => s.length <= n ? s : s.slice(0, s.lastIndexOf(" ", n)) + "…";
const ok = v => v && v !== "?" && v !== "Client" && v !== "Cliente";

const out = [];
out.push(`NAME: Felipe Bellintani. Site: bellintani.work. Email: ${S.email}.`);
out.push(`HOW HE DESCRIBES HIMSELF: ${en(S.tagline)}`);
out.push(`WHAT HE DOES: ${en(S.subline)}. Services: ${en(S.services)}.`);
out.push(`IN SHORT: ${en(S.about.intro)}`);
for (const b of S.about.credits) {
  const rows = b.rows.map(r => typeof r === "object" && !("en" in r) ? [en(r.role), en(r.name), en(r.years)].filter(Boolean).join(", ") : en(r));
  out.push(`${en(b.head).toUpperCase()}: ${rows.join(b.flow ? ", " : "; ")}.`);
}
out.push(`SOCIAL: ${S.social.map(s => `${s.label} ${s.url}`).join(", ")}.`);
if (S.homeTrack) out.push(`HOME PAGE SONG: ${S.homeTrack.name} by ${S.homeTrack.by}.`);

out.push("", "PROJECTS ON THE SITE (link a project as [Title](/p/slug/)):");
for (const p of S.projects.filter(p => !p.hidden)) {
  const slug = slugOf(p);
  const bits = [
    `- ${clean(en(p.title))} (/p/${slug}/)`,
    ok(p.client) && `client ${clean(en(p.client))}`,
    ok(p.year) && `year ${en(p.year)}`,
    ok(en(p.sector)) && `sector ${clean(en(p.sector))}`,
    ok(en(p.scope)) && `scope ${clean(en(p.scope))}`,
    ok(en(p.role)) && `his role ${clean(en(p.role))}`,
    p.tools && ok(en(p.tools)) && `tools ${clean(en(p.tools))}`,
    p.track && `soundtrack "${p.track.name}" by ${p.track.by}`,
  ].filter(Boolean);
  out.push(bits.join("; ") + ".");
  if (ok(en(p.summary))) out.push(`  About it: ${clip(clean(en(p.summary)), 520)}`);
  for (const c of p.cases || []) {
    if (c.hidden) continue;
    out.push(`  Part of it: ${clean(en(c.title))}${ok(c.year) ? ` (${en(c.year)})` : ""}${ok(en(c.summary)) ? `: ${clip(clean(en(c.summary)), 300)}` : ""}`);
  }
}

const text = out.join("\n");
fs.writeFileSync(root + "worker/facts-site.js",
  "// Generated by tools/build-facts.mjs from js/content.js. Do not edit; edit content.js or worker/facts-felipe.js.\n" +
  `export default ${JSON.stringify(text)};\n`);
console.log(`facts-site: ${text.length} chars, about ${Math.round(text.length / 4)} tokens`);
