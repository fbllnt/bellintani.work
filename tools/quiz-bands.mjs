// Band photos for the Pop quiz contact strip (Felipe, Nov 20 2026: "photographs of bands I like ... randomly").
// For each artist below (from his Last.fm top artists) it takes the Wikipedia page photo, only when it is freely
// licensed (pilicense=free: Wikimedia Commons, CC or public domain), skips logos/collages, saves an 800px JPEG in
// images/quiz-bands/ and writes js/quiz-bands.js (photo + credit) and quiz-credits.html (the attribution page).
// Run again to refresh: `node tools/quiz-bands.mjs` (macOS `sips` does the resize).
import fs from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
// Bands he likes but not his very top: his Last.fm top artists from #11 down, plus the artists of his loved tracks,
// recent plays, top albums and site soundtracks (worker/music-felipe.js). His top 10 are left out on purpose (Felipe).
import { TOP_ARTISTS, MORE_ARTISTS } from "../worker/music-felipe.js";
const ARTISTS = [...new Set([...TOP_ARTISTS.slice(10).map(([a]) => a), ...MORE_ARTISTS])];
const MUSIC = /band|musician|singer|rapper|\bdj\b|duo|group|producer|music|songwriter|composer|artist|collective|ensemble/i;
const SKIP = /logo|collage|montage|composite|interview|\.png$|\.svg$|\.gif$/i;
const UA = { "user-agent": "portfolio-quiz-builder/1.0 (static site build script)" };
const sleep = ms => new Promise(r => setTimeout(r, ms));
// Wikimedia throttles bursts: retry with growing pauses when it answers "too many requests"
const getJSON = async u => {
  for (let t = 0; t < 6; t++) {
    const r = await fetch(u, { headers: UA }), text = await r.text();
    try { return JSON.parse(text); } catch { await sleep(5000 * (t + 1)); }
  }
  return {};
};
const strip = s => String(s || "").replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();
const slug = s => s.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const found = [];
for (const artist of ARTISTS) {
  const tries = [`${artist} (band)`, `${artist} (musician)`, `${artist} (singer)`, artist];
  await sleep(600);
  const j = await getJSON("https://en.wikipedia.org/w/api.php?action=query&format=json&redirects=1&prop=pageimages|description&piprop=thumbnail|name&pithumbsize=960&pilicense=free&titles=" + encodeURIComponent(tries.join("|")));
  const pages = Object.values(j.query?.pages || {}).filter(p => !p.missing && p.pageimage && p.thumbnail && MUSIC.test(p.description || "") && !SKIP.test(p.pageimage));
  const back = {};
  for (const n of [...(j.query?.normalized || []), ...(j.query?.redirects || [])]) back[n.to] = back[n.from] || n.from;
  const rank = p => { const t = back[p.title] || p.title; const k = tries.findIndex(x => x.toLowerCase() === t.toLowerCase()); return k < 0 ? 9 : k; };
  const p = pages.sort((a, b) => rank(a) - rank(b))[0];
  if (p) found.push({ artist, file: p.pageimage, thumb: p.thumbnail.source });
}
for (let i = 0; i < found.length; i += 40) {
  const chunk = found.slice(i, i + 40);
  const j = await getJSON("https://commons.wikimedia.org/w/api.php?action=query&format=json&prop=imageinfo&iiprop=extmetadata&iiextmetadatafilter=Artist|LicenseShortName|LicenseUrl&titles=" + encodeURIComponent(chunk.map(f => "File:" + f.file).join("|")));
  const meta = {};
  for (const p of Object.values(j.query.pages)) meta[p.title.replace(/^File:/, "").replace(/ /g, "_")] = p.imageinfo?.[0]?.extmetadata || {};
  for (const f of chunk) {
    const m = meta[f.file] || {};
    f.by = strip(m.Artist?.value).slice(0, 90) || "Unknown";
    f.lic = strip(m.LicenseShortName?.value) || "Free licence";
    f.licUrl = m.LicenseUrl?.value || "";
    f.page = "https://commons.wikimedia.org/wiki/File:" + encodeURIComponent(f.file);
  }
}

const dir = root + "images/quiz-bands/";
fs.rmSync(dir, { recursive: true, force: true });
fs.mkdirSync(dir, { recursive: true });
const out = [];
for (const f of found) {
  const name = slug(f.artist) + ".jpg", path = dir + name;
  // be gentle with Wikimedia: one file at a time, with a pause, and back off when it says 429
  let r;
  for (let t = 0; t < 5; t++) { await sleep(700 + t * 3000); r = await fetch(f.thumb, { headers: UA }); if (r.status !== 429) break; }
  if (!r.ok) { console.warn("skip", f.artist, r.status); continue; }
  fs.writeFileSync(path, Buffer.from(await r.arrayBuffer()));
  try { execFileSync("sips", ["-s", "format", "jpeg", "-s", "formatOptions", "72", "--resampleWidth", "800", path, "--out", path], { stdio: "ignore" }); } catch {}
  out.push({ artist: f.artist, src: "images/quiz-bands/" + name, by: f.by, lic: f.lic, licUrl: f.licUrl, page: f.page });
}
out.sort((a, b) => a.artist.localeCompare(b.artist));

fs.writeFileSync(root + "js/quiz-bands.js", `// Generated by tools/quiz-bands.mjs: band photos for the Pop quiz strip (free licences, Wikimedia Commons). Do not edit by hand.
window.QUIZ_BANDS = ${JSON.stringify(out, null, 1)};
`);
const esc = s => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/"/g, "&quot;");
fs.writeFileSync(root + "quiz-credits.html", `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="robots" content="noindex">
<title>Pop quiz photo credits</title><style>body{margin:0;padding:40px 24px;background:#141414;color:#efede8;font:500 14px/1.5 "Inter Tight","Helvetica Neue",Arial,sans-serif}
h1{font:400 48px/1 Impact,"Anton",sans-serif;text-transform:uppercase;margin:0 0 8px}p{color:#9c9a95;max-width:640px}a{color:#ff2a1a}ul{list-style:none;padding:0;columns:2 320px;gap:32px}li{break-inside:avoid;margin:0 0 12px}b{display:block;text-transform:uppercase;letter-spacing:.02em}</style></head>
<body><h1>Photo credits</h1><p>The band photos on the <a href="/quiz">Pop quiz</a> are freely licensed images from Wikimedia Commons, shown in black and white and cropped to fit the strip. Thanks to the photographers.</p><ul>
${out.map(o => `<li><b>${esc(o.artist)}</b>Photo: ${esc(o.by)} · <a href="${esc(o.licUrl || o.page)}" rel="license noopener" target="_blank">${esc(o.lic)}</a> · <a href="${esc(o.page)}" target="_blank" rel="noopener">source</a></li>`).join("\n")}
</ul></body></html>
`);
console.log(`${out.length} band photos`);
